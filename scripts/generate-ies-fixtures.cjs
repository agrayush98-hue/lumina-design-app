// ── Distribution formulas ─────────────────────────────────────────────────────

/** Narrow/wide symmetric cosine-power distribution — returns candela at angle θ (degrees) */
function cosPow(thetaDeg, exponent) {
  const rad = thetaDeg * Math.PI / 180
  return Math.max(0, Math.cos(rad) ** exponent)
}

/** Bat-wing distribution (peaks at ~50-65°) — common for panels/troffers/linear */
function batWing(thetaDeg) {
  const rad = thetaDeg * Math.PI / 180
  // Peaks around 55°: combo of cos and sin terms
  return Math.max(0, Math.sin(rad) ** 2 * Math.cos(rad) * 3.2 + Math.cos(rad) * 0.15)
}

/** Asymmetric Lambertian (for wall washers) — stronger at low theta in one plane */
function wallWasher(thetaDeg, planeAngle) {
  const rad = thetaDeg * Math.PI / 180
  const planeRad = planeAngle * Math.PI / 180
  // Forward-heavy distribution: strongest at 30-40° from nadir in 0° plane
  const forward = Math.exp(-((thetaDeg - 35) ** 2) / 400)
  const base    = Math.max(0, Math.cos(rad)) * 0.4
  return (forward + base) * (1 - 0.5 * Math.sin(planeRad) ** 2)
}

/** Pendant — downward biased but wide (semi-direct) */
function pendant(thetaDeg) {
  const rad = thetaDeg * Math.PI / 180
  if (thetaDeg <= 90) return Math.max(0, Math.cos(rad) ** 1.5 * 0.9 + 0.05)
  // Small upward component
  const above = thetaDeg - 90
  return Math.max(0, 0.12 * Math.cos(above * Math.PI / 180) ** 2)
}

// ── IES file builder ──────────────────────────────────────────────────────────

