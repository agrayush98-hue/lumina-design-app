// ── Main ──────────────────────────────────────────────────────────────────────

function main() {
  console.log('\n⚡  IES Fixture Generator — Lumina Synth')
  console.log(`   Output: ${OUT_DIR}\n`)

  if (!fs.existsSync(OUT_DIR)) {
    fs.mkdirSync(OUT_DIR, { recursive: true })
  }

  let generated = 0
  let skipped   = 0

  for (const def of FIXTURES) {
    const fpath = path.join(OUT_DIR, def.fname)
    if (fs.existsSync(fpath)) {
      console.log(`   ⏭  ${def.fname} (already exists)`)
      skipped++
      continue
    }

    try {
      const content = buildIES(def)
      fs.writeFileSync(fpath, content, 'utf8')
      console.log(`   ✅  ${def.fname}  (${def.lumens} lm, ${def.wattage}W)`)
      generated++
    } catch (e) {
      console.log(`   ❌  ${def.fname}: ${e.message}`)
    }
  }

  console.log(`\n── Summary ────────────────────────────────────────────`)
  console.log(`   Generated : ${generated}`)
  console.log(`   Skipped   : ${skipped} (already existed)`)
  console.log(`   Total     : ${FIXTURES.length}`)
  console.log(`\n   Run parser: node scripts/parse-ies-fixtures.cjs\n`)
}

main()
