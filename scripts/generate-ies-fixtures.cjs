/**
 * Build an IESNA LM-63-2002 formatted string.
 * distFn(thetaDeg, phiDeg) → normalized candela [0..1]
 * peakCandela = total lumens / ∫∫ I(θ,φ)sinθ dθ dφ  (approx)
 */
function buildIES({ manufacturer, lumcat, luminaire, lamp, wattage, lumens, distFn, vertAngles, horizAngles }) {
  // Compute peak candela so total lumens = requested lumens
  // Numeric integration: Σ I(θ,φ) * sinθ * Δθ * 2π/numPhi
  let integral = 0
  const dTheta = Math.PI / 180  // 1° step integration
  const nPhi   = 36
  for (let t = 0; t < 180; t++) {
    const sinT = Math.sin((t + 0.5) * dTheta)
    const avgI = Array.from({ length: nPhi }, (_, p) => distFn(t + 0.5, p * 10)).reduce((a, b) => a + b, 0) / nPhi
    integral += avgI * sinT * dTheta * (2 * Math.PI)
  }
  const peakCandela = integral > 0 ? lumens / integral : lumens

  // Build candela grid: horizAngles × vertAngles
  const rows = horizAngles.map(phi =>
    vertAngles.map(theta => Math.round(distFn(theta, phi) * peakCandela * 10) / 10)
  )

  // Format rows, 10 values per line
  function fmtRow(arr) {
    const lines = []
    for (let i = 0; i < arr.length; i += 10) {
      lines.push(arr.slice(i, i + 10).map(v => v.toFixed(1).padStart(8)).join(''))
    }
    return lines.join('\n')
  }

  const nV = vertAngles.length
  const nH = horizAngles.length
  const vertStr = horizAngles.map(() => fmtRow(vertAngles)).join('\n')
  // Actually write: all vert angles once, then all horiz angles once, then candela rows
  const vertLine = vertAngles.map(v => v.toFixed(1).padStart(8)).join('')
  const horizLine = horizAngles.map(v => v.toFixed(1).padStart(8)).join('')
  const candelaSection = rows.map(row => fmtRow(row)).join('\n')

  return [
    'IESNA:LM-63-2002',
    `[TEST] SYNTH-${lumcat.replace(/\s+/g,'-')}`,
    `[MANUFAC] ${manufacturer}`,
    `[LUMCAT] ${lumcat}`,
    `[LUMINAIRE] ${luminaire}`,
    `[LAMP] ${lamp}`,
    `[WATTAGE] ${wattage}`,
    `[OTHER] Synthetic photometric data — generated by lumina-ies-generator`,
    'TILT=NONE',
    // lamp data line: numLamps lumensPerLamp multiplier numVert numHoriz photType unitsType width length height
    `1 ${lumens} 1.0 ${nV} ${nH} 1 2 0.0 0.0 0.0`,
    // ballast line: ballastFactor ballastLampFactor inputWatts
    `1.0 1.0 ${wattage}.0`,
    // Vertical angles line
    vertLine,
    // Horizontal angles line
    horizLine,
    // Candela values
    candelaSection,
    '',
  ].join('\n')
}

